package com.github.gabrielsilper.databaseviewer.form;

public class VendaForm {
    private Integer vencodigo;
    private Integer filcodigo;
    private Integer clicodigo;
    private Integer funcodigo;
    private Integer fpcodigo;
    private Integer procodigo;
    private Integer qtde = 1;

    public Integer getVencodigo() {
        return vencodigo;
    }

    public void setVencodigo(Integer vencodigo) {
        this.vencodigo = vencodigo;
    }

    public Integer getFilcodigo() {
        return filcodigo;
    }

    public void setFilcodigo(Integer filcodigo) {
        this.filcodigo = filcodigo;
    }

    public Integer getClicodigo() {
        return clicodigo;
    }

    public void setClicodigo(Integer clicodigo) {
        this.clicodigo = clicodigo;
    }

    public Integer getFuncodigo() {
        return funcodigo;
    }

    public void setFuncodigo(Integer funcodigo) {
        this.funcodigo = funcodigo;
    }

    public Integer getFpcodigo() {
        return fpcodigo;
    }

    public void setFpcodigo(Integer fpcodigo) {
        this.fpcodigo = fpcodigo;
    }

    public Integer getProcodigo() {
        return procodigo;
    }

    public void setProcodigo(Integer procodigo) {
        this.procodigo = procodigo;
    }

    public Integer getQtde() {
        return qtde;
    }

    public void setQtde(Integer qtde) {
        this.qtde = qtde;
    }
}
